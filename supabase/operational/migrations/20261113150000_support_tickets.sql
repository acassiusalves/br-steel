-- Chamados de erros e melhorias, no formato da tela de reportes do Calculaqui.
--
-- Schema próprio: os chamados nascem no PostgreSQL e não passam pela carga, pela reconciliação nem pelo
-- retorno ao Firestore. `ticket_number` é o número que o usuário vê (#42); `id` continua sendo a chave.
begin;

create schema brsteel_support;
revoke all on schema brsteel_support from public;
grant usage on schema brsteel_support to brsteel_ops_writer, brsteel_ops_reader, brsteel_ops_backup;

create table brsteel_support.tickets (
  id uuid primary key default gen_random_uuid(),
  ticket_number bigint generated by default as identity unique,
  created_by_uid text not null check (length(created_by_uid) between 1 and 200),
  -- Nome, e-mail e papel de quem abriu, como estavam na sessão no momento do envio.
  created_by jsonb not null default '{}' check (jsonb_typeof(created_by) = 'object'),
  category text not null default 'error' check (category in ('error', 'improvement')),
  description text not null check (length(description) between 1 and 4000),
  status text not null default 'pending' check (status in ('pending', 'in_progress', 'resolved')),
  source text not null default 'floating_report_button' check (length(source) between 1 and 80),
  fingerprint text not null default '' check (length(fingerprint) <= 120),
  context jsonb not null default '{}' check (jsonb_typeof(context) = 'object'),
  domain_context jsonb not null default '{}' check (jsonb_typeof(domain_context) = 'object'),
  logs jsonb not null default '[]' check (jsonb_typeof(logs) = 'array'),
  breadcrumbs jsonb not null default '[]' check (jsonb_typeof(breadcrumbs) = 'array'),
  reopen_history jsonb not null default '[]' check (jsonb_typeof(reopen_history) = 'array'),
  reopen_count integer not null default 0 check (reopen_count >= 0),
  updated_by jsonb check (updated_by is null or jsonb_typeof(updated_by) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz
);

create index tickets_created_by_created on brsteel_support.tickets (created_by_uid, created_at desc);
create index tickets_status_created on brsteel_support.tickets (status, created_at desc);
create index tickets_created on brsteel_support.tickets (created_at desc);
create index tickets_fingerprint on brsteel_support.tickets (fingerprint);

-- Quando o chamado passou a resolvido; zerado se ele for reaberto.
create function brsteel_support.tickets_touch() returns trigger language plpgsql
set search_path = pg_catalog as $$
begin
  if new.status = 'resolved' and (tg_op = 'INSERT' or old.status is distinct from 'resolved') then
    new.resolved_at := now();
  elsif new.status is distinct from 'resolved' then
    new.resolved_at := null;
  end if;
  if tg_op = 'UPDATE' then new.updated_at := now(); end if;
  return new;
end;
$$;
revoke all on function brsteel_support.tickets_touch() from public;

create trigger tickets_touch before insert or update on brsteel_support.tickets
  for each row execute function brsteel_support.tickets_touch();

alter table brsteel_support.tickets enable row level security;
revoke all on brsteel_support.tickets from public;
grant select, insert, update on brsteel_support.tickets to brsteel_ops_writer;
create policy writer on brsteel_support.tickets for all to brsteel_ops_writer using (true) with check (true);
grant select on brsteel_support.tickets to brsteel_ops_reader;
create policy reader on brsteel_support.tickets for select to brsteel_ops_reader using (true);
grant select on brsteel_support.tickets to brsteel_ops_backup;
create policy backup_reader on brsteel_support.tickets for select to brsteel_ops_backup using (true);
grant usage on sequence brsteel_support.tickets_ticket_number_seq to brsteel_ops_writer;

commit;
